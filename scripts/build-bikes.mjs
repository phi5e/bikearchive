// Builds js/bikes.js from the file names in posters/.
//
// Naming convention:  <year>_<Name_With_Underscores>.<ext>
//   2018_Mash_Steel_Fixed.jpg  ->  year "2018", name "Mash Steel Fixed"
//
// Runs automatically on GitHub whenever something in posters/ changes
// (.github/workflows/bikes.yml). Locally: node scripts/build-bikes.mjs
import { readdirSync, writeFileSync } from "node:fs";

const PATTERN = /^(\d{4})_(.+)\.(jpe?g|png|webp|avif|gif|svg)$/i;
const dir = new URL("../posters/", import.meta.url);

const bikes = [];
const skipped = [];
for (const file of readdirSync(dir).sort()) {
  if (file.startsWith(".")) continue;
  const m = file.match(PATTERN);
  if (!m) {
    skipped.push(file);
    continue;
  }
  const name = m[2].replace(/_+/g, " ").trim();
  bikes.push({ name, year: m[1], image: `posters/${file}` });
}

// Real posters first, .svg placeholders after them; within each group
// oldest first, same year sorted by name.
const isPlaceholder = (b) => b.image.toLowerCase().endsWith(".svg");
bikes.sort(
  (a, b) =>
    isPlaceholder(a) - isPlaceholder(b) ||
    a.year.localeCompare(b.year) ||
    a.name.localeCompare(b.name)
);

const lines = bikes.map((b) => `  { name: ${JSON.stringify(b.name)}, year: ${JSON.stringify(b.year)}, image: ${JSON.stringify(b.image)} },`);
const out = `/* GENERATED by scripts/build-bikes.mjs from the file names in posters/.
   Don't edit by hand: add, rename or delete images in posters/ instead,
   named <year>_<Name_With_Underscores>.<ext>, e.g. 2018_Mash_Steel_Fixed.jpg. */
window.BIKES = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("../js/bikes.js", import.meta.url), out);
console.log(`js/bikes.js: ${bikes.length} bikes`);
if (skipped.length) console.warn(`Skipped (name doesn't match <year>_<Name>.<ext>): ${skipped.join(", ")}`);
